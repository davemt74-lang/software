#!/usr/bin/env php
<?php
declare(strict_types=1);

if(PHP_SAPI!=='cli'){
    http_response_code(404);
    exit(1);
}

$mode='report';$modeChosen=false;$configPath=dirname(__DIR__).'/config.php';
foreach(array_slice($argv,1) as $argument){
    if($argument==='--help'||$argument==='-h'){
        fwrite(STDOUT,<<<'HELP'
Usage: php scripts/music-listening-v1.php [--report | --migrate] [--config=/absolute/config.php]

--report   Read-only native listening schema and coverage counts (the default).
--migrate  Install the additive ML2A session/receipt schema. Existing history stays intact.
--config   Use an existing application configuration file; defaults to config.php.

Output is JSON. No listener identities, session credentials or raw page URLs are printed.
No historical listens, royalty balances or payments are generated by this command.
Back up the database, uploads and matching code before using --migrate.
Exit codes: 0 completed, 1 unavailable/failed, 2 schema upgrade required.

HELP);
        exit(0);
    }
    if($argument==='--report'||$argument==='--migrate'){
        if($modeChosen){fwrite(STDERR,"Choose one mode: --report or --migrate.\n");exit(1);}
        $mode=substr($argument,2);$modeChosen=true;
    }elseif(str_starts_with($argument,'--config=')){
        $configPath=substr($argument,9);
    }else{
        fwrite(STDERR,"Unknown option. Use --help for supported options.\n");exit(1);
    }
}

if($configPath===''||!is_file($configPath)||!is_readable($configPath)){
    fwrite(STDERR,"Application configuration is unavailable. Use --config=/absolute/config.php.\n");exit(1);
}

define('STONEFELLOW_ROOT',dirname(__DIR__));
// Do not load the web bootstrap: a report cannot run session or request hooks.
require_once STONEFELLOW_ROOT.'/includes/music-listening-v1.php';

$stage='reading application configuration';
try{
    $config=require $configPath;
    if(!is_array($config)||!is_array($config['db']??null))throw new RuntimeException('Missing database configuration.');
    $dbConfig=$config['db'];$dsn=trim((string)($dbConfig['dsn']??''));
    if($dsn==='')throw new RuntimeException('Missing database configuration.');
    if($mode==='report'&&str_starts_with($dsn,'sqlite:')&&!is_file(substr($dsn,7))){
        fwrite(STDERR,"Read-only report requires an existing SQLite database file.\n");exit(1);
    }
    $stage='connecting to the configured database';
    $pdo=new PDO($dsn,(string)($dbConfig['user']??''),(string)($dbConfig['pass']??''),[
        PDO::ATTR_ERRMODE=>PDO::ERRMODE_EXCEPTION,
        PDO::ATTR_DEFAULT_FETCH_MODE=>PDO::FETCH_ASSOC,
        PDO::ATTR_EMULATE_PREPARES=>false,
    ]);
    $driver=(string)$pdo->getAttribute(PDO::ATTR_DRIVER_NAME);
    if(!in_array($driver,['mysql','sqlite'],true))throw new RuntimeException('Unsupported database driver.');
    if($driver==='sqlite')$pdo->exec('PRAGMA foreign_keys=ON');
    if($mode==='report'){
        $stage='reviewing listening schema and coverage';
        if($driver==='sqlite')$pdo->exec('PRAGMA query_only=ON');
        else $pdo->exec('SET SESSION TRANSACTION READ ONLY');
        $pdo->beginTransaction();
        $report=music_listening_v1_report($pdo);
        $pdo->commit();
    }else{
        $stage='installing listening session and receipt tables';
        music_listening_v1_install($pdo);
        $report=music_listening_v1_report($pdo);
    }
    fwrite(STDOUT,json_encode(['mode'=>$mode]+$report,JSON_PRETTY_PRINT|JSON_UNESCAPED_SLASHES|JSON_THROW_ON_ERROR).PHP_EOL);
    exit(music_listening_v1_schema_ready($pdo)?0:2);
}catch(Throwable $e){
    if(isset($pdo)&&$pdo instanceof PDO&&$pdo->inTransaction())$pdo->rollBack();
    fwrite(STDERR,'Music listening command failed while '.$stage.'. Check database access and playback prerequisites, then rerun --report.'.PHP_EOL);
    error_log('Music listening CLI failure: '.get_class($e).' (code '.preg_replace('/[^A-Za-z0-9_-]/','',(string)$e->getCode()).').');
    exit(1);
}
