import fs from 'node:fs';
import assert from 'node:assert/strict';
import vm from 'node:vm';

const source=fs.readFileSync('admin/stem-project-loader.js','utf8');
const sandbox={console,setTimeout,clearTimeout,Promise,URL};
sandbox.globalThis=sandbox;
vm.runInNewContext(source,sandbox);
const api=sandbox.StonefellowStemProjectLoader;
assert.ok(api,'canonical project loader API must be exported');
assert.equal(typeof api.install,'function');
assert.equal(typeof api.installProjectLoadingOverlay,'function');
assert.equal(api.install({document:{}}),false);
assert.match(source,/function installProjectLoadingOverlay\(host\)/);
assert.match(source,/Number\(audio\.readyState\|\|0\)>=4/,'loader must require HAVE_ENOUGH_DATA');
assert.match(source,/const projectReady=runtimeReady&&expectedIds\.every/);
assert.match(source,/browserWaveformMedia&&!mediaPhaseReady/);
assert.match(source,/await mediaReadyPromise/);
assert.match(source,/Audio load failed/);
assert.match(source,/Waveform load failed/);
assert.match(source,/Reload and retry/);
assert.match(source,/Continue with available tracks/);
assert.match(source,/Continue without missing waveforms/);
assert.match(source,/data-loader-failures/);
assert.match(source,/acceptedFailures/);
assert.match(source,/stonefellow:stem-playback-ready/);
assert.match(source,/originalFetchFunction/,'loader must retain the exact original fetch owner');
assert.match(source,/const restoreFetch=/,'loader must define fetch cleanup');
assert.match(source,/host\.fetch===loaderFetch/,'loader cleanup must not clobber a later fetch owner');
assert.match(source,/host\.fetch=originalFetchFunction/,'loader must restore the exact original fetch function');
assert.match(source,/restoreFetch\(\);/,'loader must release fetch ownership when readiness completes');
assert.doesNotMatch(source,/Open editor anyway|data-loader-force|forcedOpen/);
assert.match(source,/\"':'&quot;'/,'loader title escaping must emit a complete HTML quote entity');
assert.doesNotMatch(source,/createScheduler|decodeAudioData|createBufferSource/,'project loader must not own decoded-audio scheduling');
console.log('STEM_PROJECT_LOADER=PASS');
